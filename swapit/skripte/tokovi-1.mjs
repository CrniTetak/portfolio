export async function objaviOglas(S, ugaoPutanja, { naslovPrimera, nacin } = {}) {
  await S.idi(`/${ugaoPutanja}/novi-oglas/1?novi=1`)
  if (naslovPrimera) await S.izaberi('Primer oglasa', naslovPrimera)
  await S.klik('Dalje')
  proveri(`${S.uredjaj.naziv} O2 → O3`, (await S.ekran()) === 'O3')
  if (nacin) await S.klik(nacin, { sel: 'main .pilula' })
  await S.klik('Objavi')
  proveri(`${S.uredjaj.naziv} O3 → O4`, (await S.ekran()) === 'O4')
}

