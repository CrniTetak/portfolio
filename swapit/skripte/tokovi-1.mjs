// TOK 1: početna i pretraga (P1 → P3 → P7 → P4 → P5 → P6, teme P2, priče P8/P9)
// ---------------------------------------------------------------------------------------------------------------------
export async function tok1(S) {
  await korak(S, 'tok 1', async () => {
    await S.ucitaj('/ana/pocetna')
    await zdravo(S, 'P1')
    // P1 → „Vidi sve (N)“ → P7: brojač = broj kartica = „Prikazano N od N“
    const vidiSve = await S.page.evaluate(() => [...document.querySelectorAll('[data-red="knjige"] a')].map((a) => a.textContent.trim()).find((t) => /Vidi sve/.test(t)) ?? '')
    const n = Number(/\((\d+(?:\.\d+)?)\)/.exec(vidiSve)?.[1].replace('.', ''))
    await S.page.evaluate(() => [...document.querySelectorAll('[data-red="knjige"] a')].find((a) => /Vidi sve/.test(a.textContent))?.click())
    await sleep(250)
    proveri(`${S.uredjaj.naziv} P1 → P7 „Knjige“ (${vidiSve})`, (await S.ekran()) === 'P7')
    await zdravo(S, 'P7')
    const kartice = await S.broji('[data-mreza] [data-oglas]')
    proveri(`${S.uredjaj.naziv} P7: brojač „Vidi sve (${n})“ = broj kartica`, kartice === n, `${kartice} ≠ ${n}`)
    ima(S, 'P7: „Prikazano N od N“', await S.tekst(), new RegExp(`Prikazano ${n} od ${n}`))
    // čip filtera sužava, „Poništi filtere“ vraća
    await S.klik('Za poene')
    const sa = await S.broji('[data-mreza] [data-oglas]')
    proveri(`${S.uredjaj.naziv} P7: čip „Za poene“ sužava listu (${kartice} → ${sa})`, sa < kartice && sa > 0)
    await S.klik('Poništi filtere')
    // prekidač Usluge: knjige nemaju usluga → prazno stanje, ne greška
    await S.klik('Usluge')
    ima(S, 'P7: kategorija bez usluga pokazuje prazno stanje', await S.tekst(), /nema oglasa za izabranu vrstu/)
    await S.klik('Roba')

    // P3: kategorije sa brojačima, klik vodi na P7
    await S.idi('/ana/kategorije')
    await zdravo(S, 'P3')
    proveri(`${S.uredjaj.naziv} P3: 31 kategorija`, (await S.broji('[data-broj-kategorije]')) === 31)
    await S.klik('Bicikli i trotineti', { sel: 'main a' })
    proveri(`${S.uredjaj.naziv} P3 → P7`, (await S.ekran()) === 'P7')

    // P4: filteri → P5; rezultati su baš „Za poene“, a brojač = broj kartica
    await S.idi('/ana/pretraga/filteri')
    await zdravo(S, 'P4')
    await S.klik('Za poene', { sel: 'main .pilula' })
    await S.klik('Traži', { sel: 'main .red-dugmad button' })
    proveri(`${S.uredjaj.naziv} P4 → P5`, (await S.ekran()) === 'P5')
    await zdravo(S, 'P5')
    const t5 = await S.tekst()
    const brojRez = Number(/Pronađeno:\s*(\d+)/.exec(t5)?.[1])
    const poenaKartica = await S.page.evaluate(() => [...document.querySelectorAll('main [data-oglas]')].filter((k) => /Za poene/.test(k.textContent)).length)
    const svihKartica = await S.broji('main [data-oglas]')
    proveri(`${S.uredjaj.naziv} P5 „Za poene“: pronađeno ${brojRez} = broj kartica ${svihKartica}, sve su „Za poene“`, brojRez === svihKartica && poenaKartica === svihKartica && svihKartica > 0)
    // čip filtera se uklanja klikom; sortiranje menja redosled; link „Kako ređamo oglase“ vodi na P10
    await S.izaberi('Sortiranje', 'Najnovije')
    ima(S, 'P5: sortiranje je u linku', await S.hash(), /sort=najnovije/)
    await S.klik('Kako ređamo oglase', { sel: 'main a' })
    proveri(`${S.uredjaj.naziv} P5 → P10`, (await S.ekran()) === 'P10')
    await zdravo(S, 'P10')
    ima(S, 'P10: četiri parametra rangiranja i „Sponzorisano“', await S.tekst(), /Istaknuti plaćeni oglasi[\s\S]*Blizina[\s\S]*Novina[\s\S]*Poklapanje[\s\S]*Sponzorisano/)

    // slobodno kucanje u polje pretrage: radi i na računaru (zaglavlje) i na telefonu (P4)
    await S.idi(S.uredjaj.telefon ? '/ana/pretraga/filteri' : '/ana/pocetna')
    await S.trazi('bicikl')
    proveri(`${S.uredjaj.naziv} slobodno kucanje: „bicikl“ otvara P5`, (await S.ekran()) === 'P5' && /q=bicikl/.test(await S.hash()))
    const rez = await S.broji('main [data-oglas]')
    const pr = Number(/Pronađeno:\s*(\d+)/.exec(await S.tekst())?.[1])
    proveri(`${S.uredjaj.naziv} P5 „bicikl“: pronađeno = broj kartica (${pr})`, pr === rez && rez > 4)
    await S.osvezi()
    proveri(`${S.uredjaj.naziv} P5: upit u linku preživljava osvežavanje`, (await S.broji('main [data-oglas]')) === rez)
    await S.trazi('đorđe qwxz')
    ima(S, 'P5: prazan rezultat nudi „Dodaj želju“', await S.tekst(), /Nema rezultata\. Dodaj želju — javićemo kad se pojavi\./)
    // upit sa „<script>“ i znacima ostaje običan tekst
    await S.trazi('<b>"%')
    nema(S, 'P5: upit se ne izvršava kao kod', await S.page.evaluate(() => document.querySelector('main').innerHTML), /<b>"%<\/b>/)

    // „Sačuvaj pretragu“ → W6 „Pretrage“ i W3
    await S.trazi('knjige')
    await S.klik('Sačuvaj pretragu u listu želja')
    await S.idi('/ana/omiljeno')
    await S.klik('Pretrage')
    ima(S, 'W6 „Pretrage“: sačuvana pretraga je tu', await S.glavni(), /Pretrage \(1\)[\s\S]*knjige/)
    await zdravo(S, 'W6')

    // P6: mapa sa filterom iz P5 pokazuje isti broj oglasa
    await S.idi('/ana/pretraga?q=knjige')
    const rez6 = Number(/Pronađeno:\s*(\d+)/.exec(await S.tekst())?.[1])
    await S.klik('Prikaži na mapi', { sel: 'main a' })
    await zdravo(S, 'P6')
    const naMapi = Number(await S.page.evaluate(() => document.querySelector('[data-ekran-sadrzaj="P6"]')?.getAttribute('data-oglasa-na-mapi')))
    proveri(`${S.uredjaj.naziv} P6: na mapi je isto što i u rezultatima (${rez6})`, naMapi === rez6, `${naMapi} ≠ ${rez6}`)
    await S.idi('/ana/mapa')
    const sveNaMapi = Number(await S.page.evaluate(() => document.querySelector('[data-ekran-sadrzaj="P6"]')?.getAttribute('data-oglasa-na-mapi')))
    proveri(`${S.uredjaj.naziv} P6 bez filtera: svi oglasi Beograda su na mapi (225)`, sveNaMapi === 225, String(sveNaMapi))
    // klik na krug grupe lista SVE oglase iz područja („Prikaži još“ kad ih ima više)
    await S.page.evaluate(() => document.querySelector('circle[role=button][aria-label*="oglasa u području"]')?.dispatchEvent(new MouseEvent('click', { bubbles: true })))
    await sleep(200)
    ima(S, 'P6: grupa pokazuje „N oglasa u ovom području“', await S.glavni(), /\d+ oglasa u ovom području/)
    ima(S, 'P6: napomena „Prikazujemo samo približnu lokaciju“', await S.tekst(), /Prikazujemo samo približnu lokaciju/)
    ima(S, 'P6: natpis „Ilustrativna mapa“', await S.tekst(), /Ilustrativna mapa/)

    // P2: tema i jezik
    await S.idi('/ana/prikaz')
    await zdravo(S, 'P2')
    await S.klik('Svetla tema', { sel: 'main button[role=switch]' }).catch(async () => S.page.evaluate(() => document.querySelector('main button[role=switch]')?.click()))
    await sleep(200)
    proveri(`${S.uredjaj.naziv} P2: prekidač menja temu na celom demou`, (await S.page.evaluate(() => document.documentElement.getAttribute('data-tema'))) === 'tamna')
    await S.page.evaluate(() => document.querySelector('main button[role=switch]')?.click())
    await sleep(150)
    proveri(`${S.uredjaj.naziv} P2: tema se vraća na svetlu`, (await S.page.evaluate(() => document.documentElement.getAttribute('data-tema'))) === 'svetla')
    await S.izaberi('Jezik', 'Hrvatski')
    ima(S, 'P2: izbor drugog jezika samo pokazuje poruku', await S.tekst(), /Demo je na srpskom; ostali jezici dolaze u pravom proizvodu\./)

    // P8 priče i P9
    await S.idi('/ana/prica/jabuke')
    await zdravo(S, 'P8')
    ima(S, 'P8: autor i napomena', await S.glavni(), /Autor:[\s\S]*Priče su obaveštenja zajednice, ne prodaja za novac\./)
    await S.klik('Dalje')
    proveri(`${S.uredjaj.naziv} P8: Dalje otvara sledeću priču`, /prica\/knjige/.test(await S.hash()))
    await S.klik('Nazad')
    proveri(`${S.uredjaj.naziv} P8: Nazad vraća`, /prica\/jabuke/.test(await S.hash()))
    await S.idi('/ana/objavi-u-pricama')
    await zdravo(S, 'P9')
    proveri(`${S.uredjaj.naziv} P9: kvačica „Ne reklamiram…“ nije unapred štiklirana, a „Objavi“ je neaktivno`, !(await S.kvacicaStiklirana('Ne reklamiram')) && (await S.stanjeDugmeta('Objavi')) === 'neaktivno')
    await S.stikliraj('Ne reklamiram')
    await S.klik('Objavi')
    proveri(`${S.uredjaj.naziv} P9 → P1`, (await S.ekran()) === 'P1')
    ima(S, 'P1: nova priča stoji u redu priča', await S.page.evaluate(() => document.querySelector('[data-price]')?.innerText ?? ''), /Tvoja priča/)
  })
}

