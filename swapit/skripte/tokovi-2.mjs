// Tokovi 4–6: poeni i lista želja (N-1), javna aukcija i paketi, dostava. Deo skripte e2e-tokovi.mjs.
import { sleep } from './_zajednicko.mjs'
import { KORISNICI_U_POENIMA, ima, korak, nema, proveri, zdravo, C, D, SVE, rx } from './_tokovi-zajednicko.mjs'
import { objaviOglas } from './tokovi-1.mjs'

// ---------------------------------------------------------------------------------------------------------------------
// TOK 4: poeni i lista želja (W1–W6). N-1: poene dodeljuje i oduzima SWAPIT, tek posle potvrđenog prijema.
// ---------------------------------------------------------------------------------------------------------------------
export async function tok4(S) {
  await korak(S, 'tok 4', async () => {
    await S.ucitaj('/ana/lista-zelja')
    await zdravo(S, 'W3')
    ima(S, 'W3: prazna lista nudi prvu želju', await S.glavni(), /Još nemaš nijednu želju/)
    await S.klik('Dodaj želju')
    await S.klik('Dodaj', { sel: 'main [data-nova-zelja] button' })
    ima(S, 'W3: dodata želja stoji na listi sa poklapanjima', await S.glavni(), /Mali bicikl za početnike[\s\S]*Poklapanja \(\d+\)/)
    await S.klik('Poklapanja')
    proveri(`${S.uredjaj.naziv} W3 → W4`, (await S.ekran()) === 'W4')
    await zdravo(S, 'W4')
    ima(S, 'W4: „Pronađen je oglas koji odgovara tvojoj želji“', await S.glavni(), /Pronađen je oglas koji odgovara tvojoj želji: Mali bicikl za početnike/)
    await S.klik('Ne zanima me')
    await zdravo(S, 'W4 posle „Ne zanima me“')

    // W1: 20 poena, istorija samo početni poeni
    await S.idi('/ana/poeni')
    await zdravo(S, 'W1')
    ima(S, 'W1: 20 poena, model u proveri, početni poeni u istoriji', await S.glavni(), /20 poena[\s\S]*model u proveri[\s\S]*Početni poeni, potvrda telefona/)

    // „Uzmi za poene“ na stvari od 10 poena: W2 → X8 → X9 → X10
    await S.idi('/ana/oglas/setic-za-kupanje-bebe')
    await zdravo(S, 'O1 „Za poene“')
    await S.klik('Uzmi za poene')
    proveri(`${S.uredjaj.naziv} O1 → W2`, (await S.ekran()) === 'W2')
    ima(S, 'W2: imaš dovoljno poena', await S.glavni(), /Imaš dovoljno poena: 20 poena/)
    await S.klik('Uzmi za poene', { sel: 'main button' })
    proveri(`${S.uredjaj.naziv} W2 → X8`, (await S.ekran()) === 'X8')
    let st = await S.stanje()
    proveri(`${S.uredjaj.naziv} poeni se oduzimaju ODMAH (SWAPIT oduzima): potrošeno 10`, st.tokovi.poeni.length === 1 && st.tokovi.poeni[0].vrsta === 'potroseno' && st.tokovi.poeni[0].iznos === 10)
    await S.idi('/ana/poeni')
    ima(S, 'W1: 10 poena, „Potrošeno 10 poena: Setić za kupanje bebe“', await S.glavni(), /10 poena[\s\S]*Potrošeno 10 poena: Setić za kupanje bebe/)
    await S.idi('/ana/dogovor/poeni-setic-za-kupanje-bebe')
    await S.klik('Dogovor završen')
    await S.klik('Primio/la sam')
    ima(S, 'X9: primalac potvrđuje, a vlasnik (pomoćni korisnik) predaje sam', await S.glavni(), /Svi su potvrdili prijem/)
    await S.klik('Razmena obavljena')
    await zdravo(S, 'X10 „za poene“')
    ima(S, 'X10: potrošeno 10 poena', await S.glavni(), /Potrošeno 10 poena: Setić za kupanje bebe/)

    // nedovoljno poena: W2 nudi „Pokloni nešto“ koji vodi na NOVI obrazac sa izabranim „Poklanjam“
    await S.idi('/ana/poeni/nedovoljno/sklopivi-bicikl')
    await zdravo(S, 'W2 nedovoljno')
    ima(S, 'W2: fali poena i predlozi', await S.glavni(), /Imaš 10 poena, fali ti 40 poena[\s\S]*Pokloni nešto i dobij poene[\s\S]*Razmeni umesto toga[\s\S]*Dodaj u listu želja/)
    await S.klik('Pokloni nešto')
    proveri(`${S.uredjaj.naziv} W2 „Pokloni nešto“ → novi obrazac O2`, (await S.ekran()) === 'O2' && /novi=1/.test(await S.hash()))
    await S.klik('Dalje')
    proveri(`${S.uredjaj.naziv} O3: način „Poklanjam“ je preuzet iz W2`, await S.page.evaluate(() => !![...document.querySelectorAll('main .pilula')].find((p) => /Poklanjam/.test(p.textContent) && p.getAttribute('aria-pressed') === 'true')))
    await S.klik('Objavi')
    const poklonId = 'moj-ana_zvz84-1'
    // vlasnik poklona: W5 → Potvrdi poklon → X8 → X9 „Potvrđujem predaju“ → X10 → W1: SWAPIT dodeljuje tek sada
    await S.idi('/ana/poklon/' + poklonId)
    await zdravo(S, 'W5 vlasnik')
    ima(S, 'W5: zahtev za poklon stiže od drugog korisnika', await S.glavni(), /Zahtev za poklon[\s\S]*luka_zem89/)
    await S.klik('Potvrdi poklon')
    proveri(`${S.uredjaj.naziv} W5 → X8`, (await S.ekran()) === 'X8')
    st = await S.stanje()
    proveri(`${S.uredjaj.naziv} N-1: dok prijem nije potvrđen, darodavac nema dodeljene poene`, !st.tokovi.poeni.some((e) => e.vrsta === 'poklon'))
    await S.klik('Dogovor završen')
    await S.klik('Potvrđujem predaju')
    await S.klik('Razmena obavljena')
    ima(S, 'X10 (V7): SWAPIT ti je dodelio poene za poklon — primalac je potvrdio prijem (bez imena)', await S.glavni(), /SWAPIT ti je dodelio 10 poena za poklon — primalac je potvrdio prijem[.]/)
    await S.idi('/ana/poeni')
    const w1 = await S.glavni()
    ima(S, 'W1: 20 poena posle dodele, „SWAPIT ti je dodelio … za poklon“', w1, /20 poena[\s\S]*SWAPIT ti je dodelio 10 poena za poklon [(]/)
    nema(S, 'W1: nigde „od/za korisnika“ uz poene', w1, KORISNICI_U_POENIMA)
    // zahtev za tuđ poklon (Ana): W5 → „Zahtev je poslat“, trag u X12
    await S.idi('/ana/oglas/igracke-za-bebe-komplet')
    await S.klik('Zatraži poklon')
    await S.klik('Zatraži poklon', { sel: 'main button' })
    ima(S, 'W5: zahtev je poslat', await S.glavni(), /Zahtev je poslat vlasniku oglasa/)
    await S.idi('/ana/moje-razmene')
    await S.klik('Poslate ponude')
    ima(S, 'X12: zahtev za poklon je u „Poslate ponude“', await S.glavni(), /Zahtev za poklon: Igračke za bebe/)
    // W6: omiljeno (zvezdica), prati (N1)
    await S.idi('/ana/pocetna')
    await S.page.evaluate(() => document.querySelector('.ko-zvezda')?.click())
    await sleep(100)
    await S.idi('/ana/profil/marko_voz77')
    await S.klik('Prati')
    await S.idi('/ana/omiljeno')
    ima(S, 'W6: „Oglasi (1)“ i „Korisnici (1)“', await S.glavni(), /Oglasi \(1\)[\s\S]*Korisnici \(1\)/)
    await S.klik('Korisnici')
    ima(S, 'W6: „Korisnici“ sadrže pratioca', await S.glavni(), /marko_voz77/)
    await S.klik('Prestani da pratiš')
    ima(S, 'W6: „Prestani da pratiš“ uklanja', await S.glavni(), /Ne pratiš nijednog korisnika/)
  })
}

// ---------------------------------------------------------------------------------------------------------------------
// TOK 5 i 6: javna aukcija (J1–J4, Z2) i dostava (D1–D3)
// ---------------------------------------------------------------------------------------------------------------------
export async function tok5i6(S) {
  await korak(S, 'tok 5', async () => {
    await S.ucitaj('/ana/aukcije')
    await zdravo(S, 'J1')
    proveri(`${S.uredjaj.naziv} J1: šest aukcija`, (await S.broji('[data-aukcija]')) === 6)
    ima(S, 'J1: „Ponuda: 7 · ističe 12. 11. 2026.“ za MTB', await S.glavni(), /Ponuda: 7 · ističe 12\. 11\. 2026\./)
    ima(S, 'J1: zaglavlje „Javne aukcije · plaćena usluga vlasnika oglasa“ i kartice „Javna aukcija“', await S.glavni(), /Javne aukcije · plaćena usluga vlasnika oglasa[\s\S]*Javna aukcija/)
    await S.klik('MTB bicikl STORM', { sel: 'main a' })
    proveri(`${S.uredjaj.naziv} J1 → J2`, (await S.ekran()) === 'J2')
    await zdravo(S, 'J2')
    ima(S, 'J2: rok i sedam ponuda', await S.glavni(), /Ističe 12\. 11\. 2026\.[\s\S]*Ponude \(7\)/)
    // sopstveni oglas → J3 bez paketa → Z2 → Z3 → Z4 → J3 → J2 → J4 → X7
    await objaviOglas(S, 'ana')
    await S.idi('/ana/moji-oglasi')
    await S.klik('Aukcija')
    proveri(`${S.uredjaj.naziv} O6 → J3`, (await S.ekran()) === 'J3')
    await zdravo(S, 'J3 bez paketa')
    ima(S, 'S6: J3 bez paketa kaže da u paketu nema aukcija i nudi Kupi paket', await S.glavni(), /U paketu nemaš nijednu aukciju[^]*Kupi paket/)
    await S.klik('Kupi paket')
    proveri(`${S.uredjaj.naziv} J3 → Z2`, (await S.ekran()) === 'Z2')
    await zdravo(S, 'Z2')
    ima(S, 'Z2: četiri paketa sa cenama (sa PDV-om)', await S.glavni(), new RegExp([1, 3, 5, 7].map((n) => `${n}\\s*aukcij[ae]?\\s*${D(C.paketiAukcija[n]).replace('.', '\\.')}`).join('[^]*') + '[^]*sa PDV-om'))
    await S.klik('3', { sel: 'main [data-paket]' })
    await S.klik('Kupi')
    proveri(`${S.uredjaj.naziv} Z2 → Z3`, (await S.ekran()) === 'Z3')
    ima(S, 'Z3 paket: 579 din i potrošačko pravo na odustanak', await S.glavni(), rx(D(C.paketiAukcija[3]), SVE, 'Pravo na odustanak (nacrt)'))
    await S.stikliraj('Želim da usluga počne odmah')
    await S.klik('Plati')
    await S.klik('Nastavi')
    proveri(`${S.uredjaj.naziv} Z4 → J3`, (await S.ekran()) === 'J3')
    ima(S, 'S6: J3: „U paketu imaš 3; posle ove ostaje 2“', await S.glavni(), /U paketu imaš 3; posle ove ostaje 2/)
    await S.klik('Pokreni aukciju')
    proveri(`${S.uredjaj.naziv} J3 → J2 (sopstvena aukcija)`, (await S.ekran()) === 'J2')
    ima(S, 'J2: sopstvena aukcija ima unapred pripremljene ponude i „Izaberi ponudu“', await S.glavni(), /Izaberi ponudu[\s\S]*Ponude \(3\)/)
    await S.klik('Izaberi ponudu')
    proveri(`${S.uredjaj.naziv} J2 → J4`, (await S.ekran()) === 'J4')
    await zdravo(S, 'J4')
    ima(S, 'J4: „Nijedna ponuda nije automatski najbolja — biraš ti.“', await S.glavni(), /Nijedna ponuda nije automatski najbolja — biraš ti\./)
    await S.klik('Izaberi ovu ponudu')
    proveri(`${S.uredjaj.naziv} J4 → X7`, (await S.ekran()) === 'X7')
    await S.klik('Idi na dogovor')
    proveri(`${S.uredjaj.naziv} X7 → X8 (razmena iz aukcije)`, (await S.ekran()) === 'X8')
    // V2: izbor ponude na aukciji je jedina razmena za taj oglas (ostale ponude su zatvorene; test u zavrsna.test.ts)
    await S.idi('/ana/aukcije')
    proveri(`${S.uredjaj.naziv} J1: sopstvena aukcija je među aukcijama (7)`, (await S.broji('[data-aukcija]')) === 7)
    // ponuda na tuđu aukciju: J2 „Ponudi“ → X1
    await S.idi('/ana/aukcija/mtb-bicikl-storm')
    await S.klik('Ponudi')
    proveri(`${S.uredjaj.naziv} J2 „Ponudi“ → X1`, (await S.ekran()) === 'X1')
  })
  await korak(S, 'tok 6', async () => {
    await S.ucitaj('/ana/pocetna')
    await S.idi('/ana/dostava')
    await zdravo(S, 'D1')
    ima(S, 'D1: kurir ne prenosi novac, izmišljen kurir', await S.glavni(), /Kurir preuzima i isporučuje stvar; ne prenosi novac\.[\s\S]*Dunavski kurir \(izmišljeno\)/)
    await S.klik('Velika', { sel: 'main .pilula' })
    ima(S, 'D1: naknada za veliku pošiljku (ilustrativno)', await S.glavni(), rx(D(C.dostavaVelika), SVE, 'ilustrativno, nije cenovnik'))
    await S.klik('Nastavi')
    proveri(`${S.uredjaj.naziv} D1 → D2`, (await S.ekran()) === 'D2')
    await zdravo(S, 'D2')
    ima(S, 'D2: naknadu prima platforma (ne drugi korisnik)', await S.glavni(), /Naknadu prima platforma za uslugu kurirske službe; ne ide drugom korisniku\./)
    proveri(`${S.uredjaj.naziv} D2: uslovi nisu unapred štiklirani, plaćanje neaktivno`, !(await S.kvacicaStiklirana('Prihvatam uslove dostave')) && (await S.stanjeDugmeta('Plati dostavu')) === 'neaktivno')
    await S.stikliraj('Prihvatam uslove dostave')
    await S.klik('Plati dostavu')
    proveri(`${S.uredjaj.naziv} D2 → Z3`, (await S.ekran()) === 'Z3')
    ima(S, 'Z3 dostava: pružalac usluge i kurir, 590 din, potrošačko pravo', await S.glavni(), /590 din[\s\S]*SWAPIT d\.o\.o\. \(demo\), dostavu izvršava Dunavski kurir \(izmišljen\)[\s\S]*Pravo na odustanak/)
    await S.stikliraj('Želim da usluga počne odmah')
    await S.klik('Plati')
    await S.klik('Nastavi')
    proveri(`${S.uredjaj.naziv} Z4 → D3`, (await S.ekran()) === 'D3')
    await zdravo(S, 'D3')
    ima(S, 'D3: pošiljka SW-DEMO-0002', await S.glavni(), /Pošiljka SW-DEMO-0002/)
    for (let i = 0; i < 3; i++) await S.klik('Sledeća faza (demo)')
    proveri(`${S.uredjaj.naziv} D3: pošiljka je isporučena (tekuća faza je poslednja)`, (await S.page.evaluate(() => [...document.querySelectorAll('[data-posiljka] li')].map((l) => l.getAttribute('data-stanje')))).join() === 'gotovo,gotovo,gotovo,tekuce')
    // iz kamiona (desna traka / ikonska traka) vodi na D1
    await S.idi('/marko/dostava')
    await zdravo(S, 'D1 (Marko)')
  })
}
